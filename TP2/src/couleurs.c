#include <stdio.h>
#include <stdint.h>

struct couleur {
    uint8_t rouge;
    uint8_t vert;
    uint8_t bleu;
    uint8_t alpha;
};

int main(void)
{
    const struct couleur couleurs[10] = {
        {0xef, 0x78, 0x12, 0xff},
        {0x2c, 0xc8, 0x64, 0xff},
        {0x34, 0x56, 0x78, 0xff},
        {0xff, 0x00, 0x00, 0xff},
        {0x00, 0xff, 0x00, 0xff},
        {0x00, 0x00, 0xff, 0xff},
        {0xff, 0xff, 0x00, 0xff},
        {0xff, 0x00, 0xff, 0xff},
        {0x00, 0xff, 0xff, 0xff},
        {0x80, 0x80, 0x80, 0x80}
    };

    for (size_t i = 0; i < 10; ++i) {
        printf("Couleur %zu : R=%u, G=%u, B=%u, A=%u\n",
               i + 1, couleurs[i].rouge, couleurs[i].vert,
               couleurs[i].bleu, couleurs[i].alpha);
    }

    return 0;
}